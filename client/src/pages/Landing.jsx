export default function Landing() {
  const { theme, toggleTheme, scale, increaseScale, decreaseScale } = useTheme();
  const { isAuthenticated, isAdmin } = useAuth();
  const [mobileMenuOpen, setMobileMenuOpen] = useState(false);

  // Hero carousel images; img3 has a baked-in demo button that does not fit the banner.
  const heroImages = [
    '/images/header/img1.jpg',
    '/images/header/img2.jpg',
    '/images/header/img4.jpg',
    '/images/header/img5.jpg',
  ];
  const [currentSlide, setCurrentSlide] = useState(0);

  // Auto move slider every 3.5 seconds
  useEffect(() => {
    const slideInterval = setInterval(() => {
      setCurrentSlide((prev) => (prev + 1) % heroImages.length);
    }, 3500);
    return () => clearInterval(slideInterval);
  }, [heroImages.length]);

  const homeFor = isAdmin ? '/admin' : '/app';

  // Close mobile menu on resize to desktop or escape key
  useEffect(() => {
    const handleKeyDown = (e) => {
      if (e.key === 'Escape') setMobileMenuOpen(false);
    };
    const handleResize = () => {
      if (window.innerWidth > 960) setMobileMenuOpen(false);
    };
    window.addEventListener('keydown', handleKeyDown);
    window.addEventListener('resize', handleResize);
    return () => {
      window.removeEventListener('keydown', handleKeyDown);
      window.removeEventListener('resize', handleResize);
    };
  }, []);

  /* Reveal every .lm-reveal block once it scrolls into view. */
  useEffect(() => {
    const nodes = [...document.querySelectorAll('.lm-reveal')];

    if (!('IntersectionObserver' in window)) {
      nodes.forEach((node) => node.classList.add('is-in'));
      return undefined;
    }

    const observer = new IntersectionObserver(
      (entries) => {
        entries.forEach((entry) => {
          if (!entry.isIntersecting) return;
          entry.target.classList.add('is-in');
          observer.unobserve(entry.target);
        });
      },
      { threshold: 0.12 }
    );

    nodes.forEach((node) => observer.observe(node));
    return () => observer.disconnect();
  }, []);

  const closeMenu = () => setMobileMenuOpen(false);

  return (
    <div className="public landing-page" id="top">
      {/* ------------------------------------------------------------ navbar */}
      <nav className="public-nav" aria-label="Main Navigation">
        {/* Brand Logo: Gold Coin Icon + Text Spendify + Tagline */}
        <a href="#top" className="brand" onClick={closeMenu}>
          <span className="brand-mark" aria-hidden="true">S</span>
          <span>Spend<span className="brand-accent">ify</span></span>
        </a>

        {/* Desktop Links: Features, Benefits, How It Works, Sitemap */}
        <div className="nav-desktop-links">
          <a href="#top" className="nav-link">Home</a>
          <a href="#features" className="nav-link">Features</a>
          <a href="#how" className="nav-link">How It Works</a>
          <a href="#sitemap" className="nav-link">Sitemap</a>
        </div>

        {/* Desktop Actions: Login, Get Started */}
        <div className="nav-desktop-actions">
          {isAuthenticated ? (
            <Link to={homeFor}>
              <button className="nav-register-btn">
                Dashboard <Icon name="right" size={15} />
              </button>
            </Link>
          ) : (
            <>
              <Link to="/login" className="nav-login-link">
                Login
              </Link>
              <Link to="/register" className="btn-get-started" style={{ all: 'unset', cursor: 'pointer' }}>
                <span style={{ display: 'inline-flex', alignItems: 'center', gap: '8px' }}>
                  Get Started
                  <svg viewBox="0 0 24 24" width="18" height="18" aria-hidden="true">
                    <path d="M5 12h14M13 6l6 6-6 6" fill="none" stroke="currentColor"
                      strokeWidth="2.2" strokeLinecap="round" strokeLinejoin="round" />
                  </svg>
                </span>
              </Link>
            </>
          )}

          {/* Font Size (A+/A-) Control */}
          <div className="font-size-control" role="group" aria-label="Adjust font size">
            <button
              type="button"
              className="size-ctrl-btn"
              onClick={decreaseScale}
              disabled={scale <= 0.9}
              title="Decrease font size (A-)"
              aria-label="Decrease font size"
            >
              A-
            </button>
            <span className="size-ctrl-indicator" title={`Font size: ${Math.round(scale * 100)}%`}>
              {Math.round(scale * 100)}%
            </span>
            <button
              type="button"
              className="size-ctrl-btn"
              onClick={increaseScale}
              disabled={scale >= 1.3}
              title="Increase font size (A+)"
              aria-label="Increase font size"
            >
              A+
            </button>
          </div>

          {/* Dark Mode Toggle Icon */}
          <button
            type="button"
            className="theme-toggle-btn"
            onClick={toggleTheme}
            aria-label={theme === 'dark' ? 'Switch to light mode' : 'Switch to dark mode'}
            title={theme === 'dark' ? 'Switch to light mode' : 'Switch to dark mode'}
          >
            <Icon name={theme === 'dark' ? 'sun' : 'moon'} size={18} />
          </button>
        </div>

        {/* Mobile Hamburger Toggle Button */}
        <button
          type="button"
          className="mobile-hamburger-btn"
          onClick={() => setMobileMenuOpen(!mobileMenuOpen)}
          aria-label={mobileMenuOpen ? 'Close navigation menu' : 'Open navigation menu'}
          aria-expanded={mobileMenuOpen}
        >
          <Icon name={mobileMenuOpen ? 'x' : 'menu'} size={22} />
        </button>
      </nav>

      {/* Mobile Menu Dropdown & Backdrop */}
      {mobileMenuOpen && (
        <>
          <div className="mobile-menu-backdrop" onClick={closeMenu} aria-hidden="true" />
          <div className="mobile-menu-drawer" role="dialog" aria-modal="true" aria-label="Mobile Navigation">
            <div className="mobile-menu-links">
              <a href="#top" onClick={closeMenu} className="mobile-nav-link">Home</a>
              <a href="#features" onClick={closeMenu} className="mobile-nav-link">Features</a>
              <a href="#how" onClick={closeMenu} className="mobile-nav-link">How It Works</a>
              <a href="#sitemap" onClick={closeMenu} className="mobile-nav-link">Sitemap</a>
            </div>

            <div className="mobile-menu-auth">
              {isAuthenticated ? (
                <Link to={homeFor} onClick={closeMenu} className="btn btn-primary btn-block">
                  Open Dashboard
                </Link>
              ) : (
                <>
                  <Link to="/login" onClick={closeMenu} className="btn btn-outline btn-block">
                    Login
                  </Link>
                  <Link to="/register" onClick={closeMenu} className="btn btn-primary btn-block">
                    Register
                  </Link>
                </>
              )}
            </div>

            <div className="mobile-menu-controls">
              <div className="row-between">
                <span className="small muted">Dark Mode</span>
                <button
                  type="button"
                  className="theme-toggle-btn"
                  onClick={toggleTheme}
                  aria-label="Toggle dark mode"
                >
                  <Icon name={theme === 'dark' ? 'sun' : 'moon'} size={18} />
                </button>
              </div>
              <div className="row-between mt-2">
                <span className="small muted">Text Size</span>
                <div className="font-size-control">
                  <button
                    type="button"
                    className="size-ctrl-btn"
                    onClick={decreaseScale}
                    disabled={scale <= 0.9}
                    aria-label="Decrease font size"
                  >
                    A-
                  </button>
                  <span className="size-ctrl-indicator">{Math.round(scale * 100)}%</span>
                  <button
                    type="button"
                    className="size-ctrl-btn"
                    onClick={increaseScale}
                    disabled={scale >= 1.3}
                    aria-label="Increase font size"
                  >
                    A+
                  </button>
                </div>
              </div>
            </div>
          </div>
        </>
      )}

      {/* ------------------------------------------------------------ hero with full width auto-moving carousel */}
      <header className="hero-center-section">
        <h1 className="sr-only">Spendify - Smart Student Budget Tracker</h1>

        <div className="hero-picture-wrapper" style={{ position: 'relative', width: '100%' }}>
          {heroImages.map((src, idx) => (
            <img
              key={idx}
              src={src}
              alt={`Spendify Slide ${idx + 1}`}
              className="hero-picture-img"
              style={{
                width: '100%',
                display: idx === currentSlide ? 'block' : 'none',
                objectFit: 'cover'
              }}
            />
          ))}

        </div>
      </header>
      {/* -------------------------------------------------------- features */}
      <FeaturesSection />

      {/* ------------------------------------------------------------ how */}
      <section className="section" id="how">
        <div className="section-inner">
          <span className="eyebrow lm-reveal">How it works</span>
          <h2 className="mt-1 lm-reveal" style={{ '--d': '80ms' }}>
            Four steps, <span className="heading-accent">about five minutes</span>
          </h2>

          <div className="step-grid mt-4">
            {[
              { title: 'Create your account', text: 'Name, email, password. Add your academic year, usual allowance and a savings goal so the advice is tuned to you.' },
              { title: 'Log or import', text: 'Add entries as they happen, or upload a CSV of past months and let the app propose a category for every row.' },
              { title: 'Set budgets', text: 'Give your heaviest categories a monthly cap. Progress bars fill as you spend and you are warned before you pass one.' },
              { title: 'Read the monthly write-up', text: 'At any point, generate the summary for the month: what moved, what it cost you, and one thing worth changing.' }
            ].map((step, index) => (
              <div key={step.title} className="step lm-reveal" style={{ '--d': `${index * 90}ms` }}>
                <h3 style={{ fontSize: '1rem', marginBottom: '0.3rem' }}>{step.title}</h3>
                <p className="small muted">{step.text}</p>
              </div>
            ))}
          </div>
        </div>
      </section>

      {/* ------------------------------------ about, savings, cards, reviews */}
      <LandingExtras />

      {/* -------------------------------------------------------- sitemap */}
      <section className="section" id="sitemap" style={{ background: 'var(--surface-2)' }}>
        <div className="section-inner">
          <span className="eyebrow lm-reveal">Sitemap</span>
          <h2 className="mt-1 lm-reveal" style={{ '--d': '80ms' }}>
            Every page <span className="heading-accent">in the application</span>
          </h2>
          <p className="muted mt-2 lm-reveal" style={{ maxWidth: '58ch', '--d': '140ms' }}>
            The full structure of Spendify. Pages inside the dashboard ask you to sign in first.
          </p>

          <div className="sitemap mt-4">
            {SITEMAP.map((column, index) => (
              <div key={column.heading} className="sitemap-col lm-reveal" style={{ '--d': `${index * 90}ms` }}>
                <h4>{column.heading}</h4>
                <ul>
                  {column.links.map((link) => (
                    <li key={link.to + link.label}>
                      <Link to={link.to}>
                        {link.label}
                        <span>{link.note}</span>
                      </Link>
                    </li>
                  ))}
                </ul>
              </div>
            ))}
          </div>
        </div>
      </section>

      <LandingCTA />

      <footer className="public-foot landing-footer lm-reveal">
        <div className="landing-footer-main">
          <div className="landing-footer-brand">
            <a href="#top" className="brand" aria-label="Spendify home">
              <span className="brand-mark" aria-hidden="true">S</span>
              <span>Spend<span className="brand-accent">ify</span></span>
            </a>
            <p>Make student money easier to understand. Track spending, set budgets, and build better habits one month at a time.</p>
          </div>
          <div className="landing-footer-group">
            <h2>Explore</h2>
            <a href="#features">Features</a>
            <a href="#how">How it works</a>
            <a href="#sitemap">All pages</a>
          </div>
          <div className="landing-footer-group">
            <h2>Your account</h2>
            {isAuthenticated ? (
              <Link to={homeFor}>Go to dashboard</Link>
            ) : (
              <>
                <Link to="/register">Create an account</Link>
                <Link to="/login">Sign in</Link>
              </>
            )}
          </div>
        </div>
        <div className="landing-footer-bottom">
          <span>© {new Date().getFullYear()} Spendify</span>
          <a href="#top" className="landing-footer-top">Back to top <Icon name="up" size={14} /></a>
        </div>
      </footer>
    </div >
  );
}
